CREATE OR REPLACE TABLE BUSINESS_LAYER.DIM_PRODUCT AS
SELECT DISTINCT
    PRODUCT_ID,
    BRAND,
    CATEGORY,
    RATING,
    IN_STOCK,
    LAUNCH_DATE
FROM CLEANSED_LAYER.SALES_CLEAN;

CREATE OR REPLACE TABLE BUSINESS_LAYER.DIM_DATE AS
SELECT DISTINCT
    TIMESTAMP AS SALES_DATE,
    MONTH,
    QUARTER,
    WEEK,
    WEEKDAY
FROM CLEANSED_LAYER.SALES_CLEAN;

CREATE OR REPLACE TABLE BUSINESS_LAYER.FACT_SALES AS
SELECT
    SALES_ID,
    PRODUCT_ID,
    TIMESTAMP,
    REGION,
    QUANTITY,
    PRICE,
    DISCOUNT,
    TOTAL_SALES,
    ORDER_STATUS
FROM CLEANSED_LAYER.SALES_CLEAN;

CREATE OR REPLACE MATERIALIZED VIEW PRESENTATION_LAYER.MV_SALES_BY_REGION_MONTH AS
SELECT
    REGION,
    MONTH,
    SUM(TOTAL_SALES) AS TOTAL_REVENUE
FROM CLEANSED_LAYER.SALES_CLEAN
GROUP BY
    REGION,
    MONTH;

CREATE OR REPLACE MATERIALIZED VIEW PRESENTATION_LAYER.MV_TOP_PRODUCTS_BY_REVENUE AS
SELECT
    PRODUCT_ID,
    BRAND,
    CATEGORY,
    SUM(TOTAL_SALES) AS TOTAL_REVENUE
FROM CLEANSED_LAYER.SALES_CLEAN
GROUP BY
    PRODUCT_ID,
    BRAND,
    CATEGORY;

CREATE OR REPLACE MATERIALIZED VIEW PRESENTATION_LAYER.MV_REVENUE_TREND AS
SELECT
    TIMESTAMP,
    SUM(TOTAL_SALES) AS TOTAL_REVENUE
FROM CLEANSED_LAYER.SALES_CLEAN
GROUP BY
    TIMESTAMP;

CREATE OR REPLACE MATERIALIZED VIEW PRESENTATION_LAYER.MV_CATEGORY_PERFORMANCE AS
SELECT
    CATEGORY,
    COUNT(*) AS TOTAL_ORDERS,
    SUM(TOTAL_SALES) AS TOTAL_REVENUE,
    AVG(TOTAL_SALES) AS AVERAGE_SALE
FROM CLEANSED_LAYER.SALES_CLEAN
GROUP BY
    CATEGORY;