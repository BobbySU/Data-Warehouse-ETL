CREATE OR REPLACE TABLE CLEANSED_LAYER.SALES_CLEAN
(
    SALES_ID INT,
    PRODUCT_ID INT,
    REGION STRING,
    QUANTITY INT,
    PRICE NUMBER(10,2),
    TIMESTAMP TIMESTAMP_NTZ,
    DISCOUNT NUMBER(5,2),
    ORDER_STATUS STRING,
    TOTAL_SALES NUMBER(10,2),
    CATEGORY STRING,
    BRAND STRING,
    RATING FLOAT,
    IN_STOCK BOOLEAN,
    LAUNCH_DATE DATE,
    MONTH STRING,
    QUARTER STRING,
    WEEK INT,
    WEEKDAY STRING,
    SALES_BUCKET STRING
);

